# =============================================================================
# Supplementary Table S8
# Differential abundance of the top 30 bacterial species between early and
# late lactation
# =============================================================================
#
# Purpose
# -------
# Identify bacterial species whose relative abundance differs between early-
# and late-lactation milk, accounting for farm and for the paired sampling of
# the same cows at both lactation stages.
#
# Study design
# ------------
# - 42 milk samples from 21 cows sampled in early and late lactation
# - Farm A: 8 cows; Farm B: 13 cows
#
# Method
# ------
# 1. Relative abundance of each species is calculated within each sample,
#    using the whole microbial community as the denominator.
# 2. Taxa resolved to species level are retained, and the 30 species with the
#    highest mean relative abundance across all 42 samples are tested.
# 3. Zeros are replaced with a pseudocount equal to half of the smallest
#    non-zero relative abundance, and abundances are centred log-ratio (CLR)
#    transformed within each sample.
# 4. For each species, a linear mixed-effects model is fitted:
#        CLR ~ Stage + Farm + (1 | Cow)
#    Lactation stage and farm are fixed effects; cow (animal pair) is a
#    random intercept.
# 5. P values for the stage effect are obtained with Satterthwaite degrees of
#    freedom (lmerTest) and adjusted across the 30 species using the
#    Benjamini-Hochberg false discovery rate (FDR). FDR < 0.05 is considered
#    significant.
#
# Data availability
# -----------------
# Raw sequencing data are deposited in the European Nucleotide Archive (ENA)
# under project accession PRJEB127152. The species-level abundance table and
# sample metadata are generated by the QIIME 2 workflow in
# 01_milk_16S_metataxonomic_analysis/.
#
# Input files
# -----------
# data/processed/species_rel_no30.tsv
#     Rows: taxa. Column 1: Greengenes2 taxonomy string
#     ("d__...; p__...; c__...; o__...; f__...; g__...; s__...").
#     Remaining columns: one per sample (SampleID).
# data/metadata/metadata_clean.csv
#     Columns: SampleID, Sample_Name, Lactation (Early/Late), Farm (A/B).
#
# Output
# ------
# results/differential_abundance/TableS8_differential_abundance_top30_species.csv
# results/differential_abundance/R_sessionInfo.txt
#
# Usage
# -----
# Run from the root of the repository:
#     Rscript 02_downstream_R_analysis/04_differential_abundance_TableS8.R
# =============================================================================


# =============================================================================
# 0. PACKAGES
# =============================================================================

required_packages <- c("tidyverse", "lme4", "lmerTest")

missing_packages <- required_packages[
  !vapply(required_packages, requireNamespace, logical(1), quietly = TRUE)
]

if (length(missing_packages) > 0) {
  stop(
    "Missing required R packages: ",
    paste(missing_packages, collapse = ", "),
    ". Install them before running this script."
  )
}

suppressPackageStartupMessages({
  library(tidyverse)
  library(lme4)
  library(lmerTest)
})


# =============================================================================
# 1. FILE PATHS AND SETTINGS
# =============================================================================

SPECIES_FILE  <- file.path("data", "processed", "species_rel_no30.tsv")
METADATA_FILE <- file.path("data", "metadata", "metadata_clean.csv")
OUT_DIR       <- file.path("results", "differential_abundance")

dir.create(OUT_DIR, recursive = TRUE, showWarnings = FALSE)

if (!file.exists(SPECIES_FILE))  stop("Species table not found: ", SPECIES_FILE)
if (!file.exists(METADATA_FILE)) stop("Metadata file not found: ", METADATA_FILE)

TOP_N   <- 30
FDR_CUT <- 0.05


# =============================================================================
# 2. READ DATA
# =============================================================================

species_raw <- read.delim(
  SPECIES_FILE,
  sep = "\t",
  header = TRUE,
  check.names = FALSE,
  stringsAsFactors = FALSE
)

colnames(species_raw)[1] <- "Taxa"

metadata <- read.csv(METADATA_FILE, stringsAsFactors = FALSE) %>%
  mutate(across(c(SampleID, Sample_Name, Lactation, Farm),
                ~ str_trim(as.character(.x))))


# =============================================================================
# 3. SAMPLE METADATA AND EARLY-LATE PAIRS
# =============================================================================
# Cow ID is taken from Sample_Name (e.g. 180_AB and 180_AB2 -> cow 180).
# Farm is added to the cow ID so that cows with the same number on different
# farms are kept separate.

metadata <- metadata %>%
  filter(SampleID %in% colnames(species_raw)[-1]) %>%
  mutate(
    Cow   = paste(Farm, str_remove(Sample_Name, "_(AB|NI)2?$"), sep = "_"),
    Stage = factor(
      case_when(
        tolower(Lactation) == "early" ~ "Early",
        tolower(Lactation) == "late"  ~ "Late"
      ),
      levels = c("Early", "Late")
    ),
    Farm = factor(Farm, levels = c("A", "B"))
  ) %>%
  filter(!is.na(Stage), !is.na(Farm))

paired_cows <- metadata %>%
  count(Cow, Stage) %>%
  pivot_wider(names_from = Stage, values_from = n, values_fill = 0) %>%
  filter(Early == 1, Late == 1) %>%
  pull(Cow)

metadata <- metadata %>%
  filter(Cow %in% paired_cows) %>%
  arrange(Farm, Cow, Stage)

cat("Cows with early and late samples:", length(paired_cows), "\n")
cat("Samples analysed:", nrow(metadata), "\n")
print(table(Farm = metadata$Farm, Stage = metadata$Stage))

samples <- metadata$SampleID
early   <- metadata$SampleID[metadata$Stage == "Early"]
late    <- metadata$SampleID[metadata$Stage == "Late"]


# =============================================================================
# 4. SPECIES-LEVEL RELATIVE ABUNDANCE
# =============================================================================

abundance <- as.matrix(species_raw[, samples, drop = FALSE])
mode(abundance) <- "numeric"
abundance[is.na(abundance)] <- 0
abundance <- rowsum(abundance, species_raw$Taxa)

relative <- sweep(abundance, 2, colSums(abundance), "/")

get_species <- function(taxonomy) {
  vapply(taxonomy, function(x) {
    ranks <- trimws(unlist(strsplit(x, ";", fixed = TRUE)))
    if (length(ranks) < 7) return(NA_character_)
    species <- trimws(sub("^s__", "", ranks[7]))
    if (species %in% c("", "_", "__")) return(NA_character_)
    gsub("_", " ", species)
  }, character(1), USE.NAMES = FALSE)
}

species_name <- get_species(rownames(relative))
named        <- !is.na(species_name)

species_rel <- rowsum(relative[named, , drop = FALSE], species_name[named])
species_rel <- species_rel[rowSums(species_rel) > 0, , drop = FALSE]


# =============================================================================
# 5. TOP 30 SPECIES
# =============================================================================

top_species <- names(sort(rowMeans(species_rel), decreasing = TRUE))[seq_len(TOP_N)]


# =============================================================================
# 6. CLR TRANSFORMATION
# =============================================================================

pseudocount <- min(species_rel[species_rel > 0]) / 2

log_abundance <- log(species_rel + pseudocount)
clr_abundance <- sweep(log_abundance, 2, colMeans(log_abundance), "-")


# =============================================================================
# 7. LINEAR MIXED-EFFECTS MODELS
# =============================================================================

test_species <- function(species) {

  model_data <- data.frame(
    CLR   = clr_abundance[species, samples],
    Stage = metadata$Stage,
    Farm  = metadata$Farm,
    Cow   = metadata$Cow
  )

  model <- suppressMessages(
    lmer(CLR ~ Stage + Farm + (1 | Cow), data = model_data)
  )

  stage_effect <- summary(model)$coefficients["StageLate", ]

  tibble(
    Species      = species,
    Early        = 100 * mean(species_rel[species, early]),
    Late         = 100 * mean(species_rel[species, late]),
    CLR_estimate = stage_effect[["Estimate"]],
    SE           = stage_effect[["Std. Error"]],
    t            = stage_effect[["t value"]],
    P            = stage_effect[["Pr(>|t|)"]]
  )
}

results <- map_dfr(top_species, test_species) %>%
  mutate(
    Difference = Late - Early,
    FDR        = p.adjust(P, method = "BH"),
    Sig        = ifelse(FDR < FDR_CUT, "*", "ns")
  ) %>%
  arrange(P)


# =============================================================================
# 8. SUPPLEMENTARY TABLE S8
# =============================================================================

table_s8 <- results %>%
  transmute(
    Species,
    `Early (%)`        = round(Early, 3),
    `Late (%)`         = round(Late, 3),
    `Late - Early (%)` = round(Difference, 3),
    `CLR estimate`     = round(CLR_estimate, 3),
    SE                 = round(SE, 3),
    t                  = round(t, 3),
    `P-value`          = round(P, 4),
    FDR                = round(FDR, 4),
    `Sig.`             = Sig
  )

print(table_s8, n = Inf, width = Inf)

write.csv(
  table_s8,
  file.path(OUT_DIR, "TableS8_differential_abundance_top30_species.csv"),
  row.names = FALSE
)

capture.output(sessionInfo(), file = file.path(OUT_DIR, "R_sessionInfo.txt"))

cat("\nSupplementary Table S8 saved to:", OUT_DIR, "\n")
