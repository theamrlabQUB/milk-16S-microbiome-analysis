# =============================================================================
# Supplementary Table S10 and Supplementary Figure 5
# Global association between milk nutritional profile and microbial
# community composition
# =============================================================================
#
# Purpose
# -------
# Test whether the overall milk nutritional profile is associated with milk
# microbial community composition, while accounting for lactation stage and
# the paired sampling of the same cows in early and late lactation.
#
# Study design
# ------------
# - 42 milk samples from 21 cows sampled in early and late lactation
# - Farm A: 8 cows; Farm B: 13 cows
#
# Method
# ------
# 1. Community matrix: full genus-level relative-abundance table (all genera).
# 2. Nutritional traits: daily milk production, fat, energy, lactose,
#    minerals and protein, standardised to zero mean and unit variance.
# 3. Collinearity: Pearson correlation matrix and variance inflation factors.
# 4. Nutritional PCA on the standardised traits; components with an
#    eigenvalue > 1 (Kaiser criterion) are retained (checked on the scree
#    plot, Supplementary Figure 5).
# 5. Distances: Bray-Curtis (primary analysis) and binary Jaccard
#    (sensitivity analysis).
# 6. Models (vegan):
#    a) PERMANOVA (adonis2):  distance ~ Stage + NutrPC1 + NutrPC2
#       marginal tests, 9,999 permutations restricted within cow.
#    b) Partial dbRDA (capscale):
#       distance ~ Stage + NutrPC1 + NutrPC2 + Condition(Cow)
#       marginal permutation tests, 9,999 permutations.
#    Farm is not included as a separate term: each cow belongs to one farm,
#    so farm is nested within cow. Conditioning on cow (dbRDA) removes all
#    between-cow variation, including farm, and restricting permutations
#    within cow (PERMANOVA) prevents farm differences from being exchanged.
#
# Data availability
# -----------------
# Raw sequencing data are deposited in the European Nucleotide Archive (ENA)
# under project accession PRJEB127152. The feature table and taxonomy are
# generated by the QIIME 2 workflow in 01_milk_16S_metataxonomic_analysis/.
#
# Input files
# -----------
# data/processed/feature-table_milk_42samples.tsv
#     Rows: ASVs (column 1 = Feature ID). Columns: samples (SampleID).
# data/processed/taxonomy.tsv
#     QIIME 2 taxonomy export (Feature ID, Taxon).
# data/metadata/metadata_cow_name.csv
#     Columns: SampleID, CowID, Farm, Lactation (Early/Late),
#     Production, Fat, Energy, Lactose, Mineral, Protein.
#
# Outputs
# -------
# results/global_microbiome_nutrition/tables/
#     TableS10_1_Correlation_matrix.csv
#     TableS10_2_VIF.csv
#     TableS10_3a_PCA_variance_explained.csv
#     TableS10_3b_PCA_loadings.csv
#     TableS10_4_PERMANOVA_BrayCurtis.csv
#     TableS10_5_PERMANOVA_Jaccard.csv
#     TableS10_6_PartialdbRDA_BrayCurtis.csv
#     TableS10_7_PartialdbRDA_Jaccard.csv
# results/global_microbiome_nutrition/figures/
#     SupplementaryFigure5_Nutrition_PCA_Scree.png
#
# Usage
# -----
# Run from the root of the repository:
#     Rscript 02_downstream_R_analysis/05_global_microbiome_nutrition_TableS10.R
# =============================================================================


# =============================================================================
# 0. PACKAGES
# =============================================================================

required_packages <- c("tidyverse", "vegan")

missing_packages <- required_packages[
  !vapply(required_packages, requireNamespace, logical(1), quietly = TRUE)
]

if (length(missing_packages) > 0) {
  stop(
    "Missing required R packages: ",
    paste(missing_packages, collapse = ", "),
    ". Install them before running this script."
  )
}

suppressPackageStartupMessages({
  library(tidyverse)
  library(vegan)
})


# =============================================================================
# 1. FILE PATHS AND SETTINGS
# =============================================================================

FEATURE_FILE  <- file.path("data", "processed", "feature-table_milk_42samples.tsv")
TAXONOMY_FILE <- file.path("data", "processed", "taxonomy.tsv")
METADATA_FILE <- file.path("data", "metadata", "metadata_cow_name.csv")

OUT_DIR <- file.path("results", "global_microbiome_nutrition")
OUT_TAB <- file.path(OUT_DIR, "tables")
OUT_FIG <- file.path(OUT_DIR, "figures")

dir.create(OUT_TAB, recursive = TRUE, showWarnings = FALSE)
dir.create(OUT_FIG, recursive = TRUE, showWarnings = FALSE)

for (f in c(FEATURE_FILE, TAXONOMY_FILE, METADATA_FILE)) {
  if (!file.exists(f)) stop("Input file not found: ", f)
}

N_PERM <- 9999
set.seed(12345)

NUTRITION_VARS <- c("Production", "Fat", "Energy", "Lactose", "Mineral", "Protein")


# =============================================================================
# 2. METADATA
# =============================================================================

meta <- read.csv(METADATA_FILE, stringsAsFactors = FALSE, check.names = FALSE)
meta <- meta[, !(is.na(names(meta)) | trimws(names(meta)) == ""), drop = FALSE]
names(meta) <- trimws(names(meta))

required_cols <- c("SampleID", "CowID", "Farm", "Lactation", NUTRITION_VARS)
missing_cols  <- setdiff(required_cols, names(meta))
if (length(missing_cols) > 0) {
  stop("Missing metadata columns: ", paste(missing_cols, collapse = ", "))
}

meta <- meta %>%
  mutate(
    SampleID = trimws(as.character(SampleID)),
    CowID    = factor(paste(trimws(Farm), trimws(CowID), sep = "_")),
    Farm     = factor(trimws(Farm)),
    Stage    = factor(
      case_when(
        tolower(trimws(Lactation)) == "early" ~ "Early",
        tolower(trimws(Lactation)) == "late"  ~ "Late"
      ),
      levels = c("Early", "Late")
    ),
    across(all_of(NUTRITION_VARS), ~ as.numeric(.x))
  ) %>%
  filter(!is.na(Stage))


# =============================================================================
# 3. CHECK THE COW PAIRING
# =============================================================================
# Each cow must contribute exactly one early and one late sample.

pairing <- meta %>%
  group_by(CowID) %>%
  summarise(n_early = sum(Stage == "Early"), n_late = sum(Stage == "Late"),
            .groups = "drop")

unpaired <- pairing %>% filter(n_early != 1 | n_late != 1)
if (nrow(unpaired) > 0) {
  print(as.data.frame(unpaired))
  stop("Each cow must have exactly one early and one late sample.")
}

cat("Cows:", nrow(pairing), "| Samples:", nrow(meta), "\n")


# =============================================================================
# 4. GENUS-LEVEL COMMUNITY MATRIX
# =============================================================================

features <- read.delim(FEATURE_FILE, sep = "\t", header = TRUE,
                       check.names = FALSE, stringsAsFactors = FALSE, quote = "")
counts <- as.matrix(features[, -1, drop = FALSE])
mode(counts) <- "numeric"
rownames(counts) <- as.character(features[[1]])

taxonomy <- read.delim(TAXONOMY_FILE, sep = "\t", header = TRUE,
                       check.names = FALSE, stringsAsFactors = FALSE, quote = "")
names(taxonomy)[1] <- "FeatureID"
names(taxonomy)[names(taxonomy) == "Taxon"] <- "Taxon"

get_genus <- function(taxon) {
  vapply(taxon, function(x) {
    ranks <- trimws(unlist(strsplit(x, ";", fixed = TRUE)))
    genus <- ranks[grepl("^g__", ranks)]
    if (length(genus) == 0) return(NA_character_)
    genus <- trimws(sub("^g__", "", genus[1]))
    if (genus %in% c("", "_", "__")) return(NA_character_)
    gsub("_", " ", genus)
  }, character(1), USE.NAMES = FALSE)
}

samples <- intersect(colnames(counts), meta$SampleID)
if (length(samples) != 42) stop("Expected 42 matched samples; found ", length(samples), ".")

meta   <- meta[match(samples, meta$SampleID), , drop = FALSE]
counts <- counts[, samples, drop = FALSE]
counts <- counts[rownames(counts) %in% taxonomy$FeatureID, , drop = FALSE]

genus <- get_genus(taxonomy$Taxon[match(rownames(counts), taxonomy$FeatureID)])

relative <- sweep(counts, 2, colSums(counts), "/") * 100
genus_mat <- rowsum(relative[!is.na(genus), , drop = FALSE], genus[!is.na(genus)])

community <- t(genus_mat)[meta$SampleID, , drop = FALSE]

cat("Community matrix:", nrow(community), "samples x", ncol(community), "genera\n")


# =============================================================================
# 5. NUTRITIONAL TRAITS: COLLINEARITY AND PCA
# =============================================================================

nutrition <- meta[, NUTRITION_VARS]
if (anyNA(nutrition)) stop("Missing values in the nutritional traits.")

# 5a. Pearson correlation matrix (Table S10.1)
cor_mat <- cor(nutrition, method = "pearson")
write.csv(round(cor_mat, 2), file.path(OUT_TAB, "TableS10_1_Correlation_matrix.csv"))

# 5b. Variance inflation factors (Table S10.2)
vif <- sapply(NUTRITION_VARS, function(v) {
  model <- lm(reformulate(setdiff(NUTRITION_VARS, v), response = v), data = nutrition)
  1 / (1 - summary(model)$r.squared)
})
write.csv(data.frame(Variable = names(vif), VIF = round(vif, 2)),
          file.path(OUT_TAB, "TableS10_2_VIF.csv"), row.names = FALSE)

# 5c. PCA on standardised traits (Table S10.3)
pca <- prcomp(nutrition, center = TRUE, scale. = TRUE)
eigenvalues <- pca$sdev^2

variance_table <- data.frame(
  PC                       = colnames(pca$x),
  Eigenvalue               = round(eigenvalues, 3),
  `Proportion of Variance` = round(eigenvalues / sum(eigenvalues), 3),
  `Cumulative Variance`    = round(cumsum(eigenvalues) / sum(eigenvalues), 3),
  check.names = FALSE
)
write.csv(variance_table, file.path(OUT_TAB, "TableS10_3a_PCA_variance_explained.csv"),
          row.names = FALSE)

n_pc <- sum(eigenvalues > 1)
cat("Nutritional PCs retained (eigenvalue > 1):", n_pc, "\n")

write.csv(round(pca$rotation[, seq_len(n_pc), drop = FALSE], 3),
          file.path(OUT_TAB, "TableS10_3b_PCA_loadings.csv"))

# Scree plot (Supplementary Figure 5)
png(file.path(OUT_FIG, "SupplementaryFigure5_Nutrition_PCA_Scree.png"),
    width = 6, height = 5, units = "in", res = 300)
plot(eigenvalues, type = "b", pch = 19, xaxt = "n",
     xlab = "Principal component", ylab = "Eigenvalue",
     main = "Scree plot: milk nutritional PCA")
axis(1, at = seq_along(eigenvalues))
abline(h = 1, lty = 2, col = "red")
dev.off()

pc_terms <- paste0("NutrPC", seq_len(n_pc))
for (i in seq_len(n_pc)) meta[[pc_terms[i]]] <- pca$x[, i]


# =============================================================================
# 6. COMMUNITY DISTANCES
# =============================================================================

distances <- list(
  BrayCurtis = vegdist(community, method = "bray"),
  Jaccard    = vegdist(community, method = "jaccard", binary = TRUE)
)


# =============================================================================
# 7. PERMANOVA WITH PERMUTATIONS RESTRICTED WITHIN COW (Tables S10.4-S10.5)
# =============================================================================

permanova_formula <- reformulate(c("Stage", pc_terms), response = "dist_obj")
within_cow <- how(blocks = meta$CowID, nperm = N_PERM)

table_number <- c(BrayCurtis = "4", Jaccard = "5")

for (d in names(distances)) {
  dist_obj <- distances[[d]]
  fit <- adonis2(permanova_formula, data = meta, permutations = within_cow,
                 by = "margin")
  cat("\nPERMANOVA,", d, "\n"); print(fit)
  write.csv(as.data.frame(fit),
            file.path(OUT_TAB, paste0("TableS10_", table_number[d], "_PERMANOVA_", d, ".csv")))
}


# =============================================================================
# 8. PARTIAL dbRDA CONDITIONED ON COW (Tables S10.6-S10.7)
# =============================================================================

dbrda_formula <- as.formula(
  paste("dist_obj ~", paste(c("Stage", pc_terms), collapse = " + "), "+ Condition(CowID)")
)

table_number <- c(BrayCurtis = "6", Jaccard = "7")

for (d in names(distances)) {
  dist_obj <- distances[[d]]
  model <- capscale(dbrda_formula, data = meta)
  test  <- anova.cca(model, by = "margin", permutations = N_PERM)
  cat("\nPartial dbRDA,", d, "\n"); print(test)
  write.csv(as.data.frame(test),
            file.path(OUT_TAB, paste0("TableS10_", table_number[d], "_PartialdbRDA_", d, ".csv")))
}


# =============================================================================
# 9. SESSION INFORMATION
# =============================================================================

capture.output(sessionInfo(), file = file.path(OUT_TAB, "R_sessionInfo.txt"))

cat("\nTables saved to:", OUT_TAB, "\nFigure saved to:", OUT_FIG, "\n")
